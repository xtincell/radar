-- Décisions La Barre lues par Radar — SHK-0005, sens 1, arbitrage 5.5 (11 novembre 2026).
-- Appliqué à chaque démarrage par initDb (server/pgrest.js), après journal.sql ;
-- idempotent. Aucune écriture dans briefs ni dans task_events : une décision ne
-- part dans aucun flux (functions/_feed.js), privé par défaut depuis l'arbitrage 5.7.

-- Reçus : une ligne par version d'une décision, jamais réécrite ni effacée.
-- Clé : (instance La Barre, identifiant de la décision, version). Une décision
-- relue à l'identique ne produit rien ; une décision changée produit la version
-- suivante ; une décision absente de La Barre produit une version « retiree »,
-- qui reprend ses champs descriptifs sans contenu.
create table if not exists barre_recus (
  id bigint generated by default as identity primary key,
  barre_instance text not null,
  decision_id text not null,
  version int not null check (version >= 1),
  etat text not null check (etat in ('recue','retiree')),
  empreinte text,            -- empreinte_contenu servie par La Barre ; null pour un retrait
  projet text,               -- identifiant du projet La Barre (decision.projet), tel quel
  quand timestamptz,         -- date de la décision ; null si quand_declare n'est pas une date ISO 8601
  quand_declare text,        -- valeur de quand reçue, intacte
  type text, verdict text, titre text, motif text,
  qui text,                  -- poste titulaire déclaré par La Barre
  acteur jsonb,              -- auteur tel que déclaré (personneId, nom, poste)
  remplace text,             -- décision que celle-ci supplante, selon La Barre
  contenu jsonb,             -- décision servie, sans son empreinte
  at timestamptz not null default now(),   -- heure d'écriture dans Radar, distincte de quand
  unique (barre_instance, decision_id, version)
);
create index if not exists barre_recus_projet_idx on barre_recus (barre_instance, projet);
create index if not exists barre_recus_remplace_idx on barre_recus (barre_instance, remplace);

-- Correspondance projet La Barre ↔ dossier Radar, tenue dans Radar par un
-- superviseur. Jamais déduite d'un code ndeg : sans ligne ici, une décision
-- reste « non rattachée ». radar_instance nomme l'instance dont brief_id est
-- l'identifiant, posé par le serveur.
create table if not exists barre_projets (
  id bigint generated by default as identity primary key,
  barre_instance text not null,
  projet text not null,
  radar_instance text not null,
  brief_id bigint not null,
  created_by text,
  created_at timestamptz not null default now(),
  unique (barre_instance, projet)
);

-- État de la dernière lecture par instance : l'ETag reçu (qui survit au
-- redémarrage), la base de référence lue, et le compte rendu.
create table if not exists barre_lectures (
  barre_instance text primary key,
  etag text, depot text, maison text,
  lu_le timestamptz, statut text, message text,
  recues int, nouvelles int, versions int, inchangees int, retirees int, refusees int, ecartees int,
  derniere_reussite timestamptz
);

-- Lecture : toutes les versions, la courante marquée, le rattachement calculé
-- à la lecture depuis la correspondance — une correspondance ajoutée plus tard
-- rattache aussi les décisions déjà reçues.
create or replace view barre_decisions as
select r.id, r.barre_instance, r.decision_id, r.version, r.etat,
  (r.version = max(r.version) over (partition by r.barre_instance, r.decision_id)) as courante,
  r.empreinte, r.projet, r.quand, r.quand_declare, r.type, r.verdict, r.titre, r.motif, r.qui, r.acteur, r.remplace,
  (select s.decision_id from barre_recus s
    where s.barre_instance = r.barre_instance and s.remplace = r.decision_id and s.etat = 'recue'
      and s.version = (select max(t.version) from barre_recus t where t.barre_instance = s.barre_instance and t.decision_id = s.decision_id)
    order by s.decision_id limit 1) as remplacee_par,
  r.contenu, r.at, m.brief_id,
  case when coalesce(r.projet, '') = '' then 'sans_projet'
       when m.id is null then 'non_rattachee'
       when not exists (select 1 from briefs b where b.id = m.brief_id) then 'dossier_introuvable'
       else 'rattachee' end as rattachement
from barre_recus r
left join barre_projets m on m.barre_instance = r.barre_instance and m.projet = r.projet;

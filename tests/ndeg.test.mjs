test('la migration est idempotente : relancée puis redémarrée, elle ne change rien', async () => {
  const photo = async () => Object.fromEntries(await Promise.all(['briefs', 'comments', 'brief_assets', 'task_events']
    .map(async t => [t, await table(t)]).concat([(async () => ['trace', await table('briefs_ndeg_renommes', 'brief_id')])()])));
  const avantRejeu = await photo();
  const migration = await readFile(new URL('../server/ndeg.sql', import.meta.url), 'utf8');
  for (let i = 0; i < 2; i++) {
    const resultats = await db.query(migration);
    const dernier = (Array.isArray(resultats) ? resultats : [resultats]).at(-1).rows[0];
    assert.deepEqual(dernier, { doublons: 0, renommes: 0, ambigus: 0, contrainte_posee: false });
  }
  await stopChild(); await startChild();
  assert.deepEqual(await photo(), avantRejeu);
  assert.doesNotMatch(childLogs, /dossier\(s\) renommé\(s\)/);
});

test('un POST rejoué avec un code existant est refusé en 409, sans dossier ni événement', async () => {
  const premier = await req('/rest/v1/briefs', 'alice', 'POST', { ndeg: 'NOUV-1', projet: 'Création unique', statut: 'Reçu' });
  assert.equal(premier.status, 201);
  const rejeu = await req('/rest/v1/briefs', 'alice', 'POST', { ndeg: 'NOUV-1', projet: 'Création rejouée', statut: 'Reçu' });
  assert.equal(rejeu.status, 409);
  const corps = await rejeu.json();
  assert.equal(corps.ndeg, 'NOUV-1'); assert.match(corps.message, /NOUV-1/);
  assert.equal((await db.query("select count(*)::int as n from briefs where ndeg='NOUV-1'")).rows[0].n, 1);
  assert.equal((await db.query("select count(*)::int as n from task_events where ndeg='NOUV-1'")).rows[0].n, 1);
  // Un lot qui répète un code est refusé entier.
  assert.equal((await req('/rest/v1/briefs', 'alice', 'POST', [{ ndeg: 'NOUV-2', projet: 'Un' }, { ndeg: 'NOUV-2', projet: 'Deux' }])).status, 409);
  assert.equal((await db.query("select count(*)::int as n from briefs where ndeg='NOUV-2'")).rows[0].n, 0);
  // Le code d'un dossier privé est pris, sans que son contenu ne soit révélé.
  const prive = await req('/rest/v1/briefs', 'sue', 'POST', { ndeg: 'DUP-1-4', projet: 'Collision' });
  assert.equal(prive.status, 409); assert.ok(!(await prive.text()).includes('DUP_SECOND_PRIVE'));
  // Des POST simultanés : un seul dossier.
  const rs = await Promise.all([1, 2, 3, 4, 5].map(n => req('/rest/v1/briefs', 'machine', 'POST', { ndeg: 'NOUV-3', projet: 'Course ' + n })));
  assert.deepEqual(rs.map(r => r.status).sort(), [201, 409, 409, 409, 409]);
  assert.equal((await db.query("select count(*)::int as n from briefs where ndeg='NOUV-3'")).rows[0].n, 1);
  assert.equal((await db.query("select count(*)::int as n from task_events where ndeg='NOUV-3'")).rows[0].n, 1);
});


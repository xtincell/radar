test('aucun événement n’est perdu ; chaque renommage laisse sa trace confidentielle', async () => {
  const events = await table('task_events');
  // Les événements antérieurs restent identiques ; seules les colonnes de revue
  // ajoutées par journal.sql apparaissent, vides.
  const anciens = events.slice(0, avant.task_events.length);
  assert.ok(anciens.every(e => e.revue_par === null && e.revue_le === null));
  assert.deepEqual(anciens.map(({ revue_par, revue_le, ...e }) => e), avant.task_events);
  const nouveaux = events.slice(avant.task_events.length);
  assert.equal(nouveaux.length, 5);
  assert.ok(nouveaux.every(e => e.kind === 'renamed'));
  const pour = k => nouveaux.find(e => Number(e.brief_id) === ids[k]);
  assert.equal(pour('C').ndeg, 'DUP-1-4'); assert.match(pour('C').summary, /DUP-1 → DUP-1-4/);
  assert.equal(pour('C').private_to, 'Alice Recette');
  assert.equal(pour('A').private_to, '');
  assert.ok(pour('A').scope_snapshot);
  // Le renommage d'un dossier privé ne se lit que dans son périmètre.
  assert.equal((await (await req('/rest/v1/task_events?kind=eq.renamed&ndeg=eq.DUP-1-4', 'alice')).json()).length, 1);
  assert.deepEqual(await (await req('/rest/v1/task_events?kind=eq.renamed&ndeg=eq.DUP-1-4', 'sue')).json(), []);
});


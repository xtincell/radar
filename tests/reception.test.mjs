test('SQL, REST et import utilisent le même journal, sans doublon ni faux mouvement', async () => {
  const created = await (await req('/rest/v1/briefs', 'alice', 'POST', { ndeg: 'REC-UNIQUE', projet: 'Manuel', statut: 'Reçu' })).json();
  const id = created[0].id;
  assert.equal((await db.query('select count(*)::int as n from task_events where brief_id=$1', [id])).rows[0].n, 1);
  assert.equal((await req('/rest/v1/briefs?id=eq.' + id, 'alice', 'PATCH', { statut: 'Reçu' })).status, 200);
  assert.equal((await db.query('select count(*)::int as n from task_events where brief_id=$1', [id])).rows[0].n, 1);
  await db.query('update briefs set statut=$1 where id=$2', ['En cours', id]);
  const events = (await db.query('select kind,statut_old,statut_new from task_events where brief_id=$1 order by id', [id])).rows;
  assert.deepEqual(events.map(e=>e.kind), ['created','status']);
  assert.equal(events[1].statut_old, 'Reçu'); assert.equal(events[1].statut_new, 'En cours');
  const ingest = await req('/ingest', 'alice', 'POST', { text: 'Retour synthétique brut conservé, sans modèle.', client: 'Recette' });
  assert.equal(ingest.status, 201); const result = await ingest.json(); assert.equal(result.fallback, true);
  assert.equal((await db.query('select count(*)::int as n from task_events where ndeg=$1',[result.created[0].ndeg])).rows[0].n, 1);
});


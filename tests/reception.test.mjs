test('un dossier devenu privé masque son ancien journal public, même après suppression privée', async () => {
  await db.query("insert into briefs(ndeg,projet) values ('REC-FERME','PUBLIC_PUIS_PRIVE')");
  assert.ok((await (await req('/activity.json',null)).text()).includes('PUBLIC_PUIS_PRIVE'));
  await db.query("update briefs set private_to='Alice Recette' where ndeg='REC-FERME'");
  assert.ok(!(await (await req('/activity.json',null)).text()).includes('PUBLIC_PUIS_PRIVE'));
  assert.deepEqual(await (await req('/rest/v1/task_events?ndeg=eq.REC-FERME','bob')).json(),[]);
  await db.query("delete from briefs where ndeg='REC-FERME'");
  assert.ok(!(await (await req('/activity.json',null)).text()).includes('PUBLIC_PUIS_PRIVE'));
  assert.deepEqual(await (await req('/rest/v1/task_events?ndeg=eq.REC-FERME','bob')).json(),[]);
  assert.equal((await (await req('/rest/v1/task_events?ndeg=eq.REC-FERME')).json()).length,3);
});

